from __future__ import annotations

import json
import random
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Optional, Tuple

import chess


@dataclass
class GeneratedChessScenario:
    name: str
    payload: dict[str, Any]
    is_legal: bool


class ChessScenarioGenerator:
    """Utility for producing labeled chess move legality scenarios."""

    def __init__(self, *, min_plies: int = 4, max_plies: int = 24, seed: Optional[int] = None) -> None:
        if min_plies < 0:
            raise ValueError("min_plies must be non-negative")
        if max_plies < min_plies:
            raise ValueError("max_plies must be >= min_plies")
        self.min_plies = min_plies
        self.max_plies = max_plies
        self.rng = random.Random(seed)

    def generate_batch(self, *, legal_count: int, illegal_count: int) -> list[GeneratedChessScenario]:
        if legal_count < 0 or illegal_count < 0:
            raise ValueError("legal_count and illegal_count must be non-negative")
        scenarios: list[GeneratedChessScenario] = []
        for idx in range(legal_count):
            scenarios.append(self._generate_scenario(is_legal=True, index=idx + 1))
        for idx in range(illegal_count):
            scenarios.append(self._generate_scenario(is_legal=False, index=idx + 1))
        return scenarios

    def write_scenarios(self, scenarios: list[GeneratedChessScenario], output_dir: Path) -> list[Path]:
        output_dir.mkdir(parents=True, exist_ok=True)
        written: list[Path] = []
        for scenario in scenarios:
            path = output_dir / f"{scenario.name}.json"
            with path.open("w", encoding="utf-8") as fh:
                json.dump(scenario.payload, fh, indent=2, ensure_ascii=False)
            written.append(path)
        return written

    def _generate_scenario(self, *, is_legal: bool, index: int) -> GeneratedChessScenario:
        board = self._random_board()
        if is_legal:
            candidate_move = self._random_legal_move(board)
            label = "legal"
            context = (
                f"Autogenerated legal move for {'white' if board.turn else 'black'} to move "
                f"after {board.fullmove_number - 1} completed moves."
            )
        else:
            candidate_move, reason = self._random_illegal_move(board)
            label = "illegal"
            context = (
                f"Autogenerated illegal move while {'white' if board.turn else 'black'} is on move. "
                f"Reason: {reason}."
            )
        payload = {
            "position_fen": board.fen(),
            "candidate_move": candidate_move,
            "move_context": context,
            "expected_legality": label,
        }
        name = f"{label}_{index:03d}"
        return GeneratedChessScenario(name=name, payload=payload, is_legal=is_legal)

    def _random_board(self) -> chess.Board:
        attempts = 0
        while attempts < 200:
            attempts += 1
            board = chess.Board()
            plies = self.rng.randint(self.min_plies, self.max_plies) if self.max_plies > 0 else 0
            for _ in range(plies):
                if board.is_game_over():
                    break
                moves = list(board.legal_moves)
                if not moves:
                    break
                board.push(self.rng.choice(moves))
            if board.is_game_over() or len(list(board.legal_moves)) == 0:
                continue
            return board
        raise RuntimeError("Failed to generate a playable board state after many attempts")

    def _random_legal_move(self, board: chess.Board) -> str:
        moves = list(board.legal_moves)
        if not moves:
            raise RuntimeError("Board has no legal moves to choose from")
        move = self.rng.choice(moves)
        return board.san(move)

    def _random_illegal_move(self, board: chess.Board) -> Tuple[str, str]:
        legal_uci = {move.uci() for move in board.legal_moves}
        opponent_color = not board.turn
        opponent_squares = [sq for sq in chess.SQUARES if board.color_at(sq) == opponent_color]
        if opponent_squares:
            from_sq = self.rng.choice(opponent_squares)
            to_sq = self.rng.choice(chess.SQUARES)
            move = chess.Move(from_sq, to_sq)
            candidate = move.uci()
            if candidate not in legal_uci:
                mover = "white" if opponent_color else "black"
                return candidate, f"tries to move a {mover} piece when it is {('white' if board.turn else 'black')}'s turn"
        own_squares = [sq for sq in chess.SQUARES if board.color_at(sq) == board.turn]
        attempts = 0
        while attempts < 200 and own_squares:
            attempts += 1
            from_sq = self.rng.choice(own_squares)
            to_sq = self.rng.choice(chess.SQUARES)
            promotion = None
            if board.piece_type_at(from_sq) == chess.PAWN and chess.square_rank(to_sq) in (0, 7):
                promotion = self.rng.choice([chess.QUEEN, chess.ROOK, chess.BISHOP, chess.KNIGHT])
            move = chess.Move(from_sq, to_sq, promotion)
            candidate = move.uci()
            if candidate not in legal_uci:
                return candidate, "the destination square or promotion choice is not legal from that piece and position"
        legal_moves = list(board.legal_moves)
        if not legal_moves:
            raise RuntimeError("Board has no legal moves to mutate into illegal form")
        move = self.rng.choice(legal_moves)
        file_idx = (chess.square_file(move.to_square) + 2) % 8
        rank_idx = chess.square_rank(move.to_square)
        tweaked = chess.Move(move.from_square, chess.square(file_idx, rank_idx), move.promotion)
        return tweaked.uci(), "mutated from a legal move to land on an unreachable square"
